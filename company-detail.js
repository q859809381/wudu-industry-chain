function renderTaxTrendChart(width, height) {
  const w = Math.max(200, Math.round(width));
  const h = Math.max(140, Math.round(height));
  const plotLeft = 46;
  const plotRight = Math.max(plotLeft + 80, w - 14);
  const plotTop = 24;
  const plotBottom = Math.max(plotTop + 40, h - 26);
  const maxValue = 20000;
  const yFor = (value) => plotBottom - (value / maxValue) * (plotBottom - plotTop);
  const step = (plotRight - plotLeft) / (taxTrendData.length - 1);
  const points = taxTrendData.map((point, index) => ({ x: Math.round(plotLeft + index * step), y: yFor(point.value) }));
  let linePath = `M${points[0].x},${points[0].y.toFixed(1)}`;
  for (let index = 1; index < points.length; index += 1) {
    const cx = Math.round((points[index - 1].x + points[index].x) / 2);
    linePath += ` C${cx},${points[index - 1].y.toFixed(1)} ${cx},${points[index].y.toFixed(1)} ${points[index].x},${points[index].y.toFixed(1)}`;
  }
  const lastPoint = points[points.length - 1];
  const areaPath = `${linePath} L${lastPoint.x},${plotBottom} L${points[0].x},${plotBottom} Z`;
  const yTicks = [0, 4000, 8000, 12000, 16000, 20000];
  const dots = points.map((point, index) => `<circle cx="${point.x}" cy="${point.y.toFixed(1)}" r="${index === points.length - 1 ? 4.5 : 3.5}" fill="${index === points.length - 1 ? "#1d6fd6" : "#fff"}" stroke="#2f9be0" stroke-width="2" />`).join("");
  const xLabels = points.map((point, index) => `<text x="${point.x}" y="${plotBottom + 16}" text-anchor="middle">${taxTrendData[index].year}</text>`).join("");
  const yLabels = yTicks.map((tick) => `<text x="${plotLeft - 8}" y="${(yFor(tick) + 4).toFixed(1)}" text-anchor="end">${tick}</text>`).join("");
  return `<svg viewBox="0 0 ${w} ${h}" preserveAspectRatio="none" role="img" aria-label="财税趋势图" class="detail-tax-chart-svg"><text x="${plotLeft - 8}" y="13" class="detail-tax-chart-unit" text-anchor="start">单位：万元</text><line x1="${plotLeft}" y1="${plotBottom}" x2="${plotRight}" y2="${plotBottom}" stroke="#e3e7f2" />${yLabels}<path d="${areaPath}" fill="#54b7ef" fill-opacity="0.85" /><path d="${linePath}" fill="none" stroke="#2f9be0" stroke-width="2.5" />${dots}${xLabels}</svg>`;
}

