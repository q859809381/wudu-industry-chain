function getDetailSortLabel(column, direction) {
  if (!direction) return `点击按${column}排序`;
  return direction === "asc" ? `已按${column}升序排列，再点击恢复默认顺序` : `已按${column}降序排列，再点击切换为升序`;
}

function applyDetailSort(itemId) {
  const state = detailPaginationState.get(itemId);
  if (!state) return;
  const sort = detailSortState.get(itemId);
  const columnIndex = sort ? state.preset.columns.indexOf(sort.column) : -1;
  if (sort && columnIndex < 0) return;
  if (sort) {
    const type = (detailSortableColumns[itemId] || {})[sort.column] || "text";
    const direction = sort.direction === "asc" ? 1 : -1;
    state.rows = state.baseRows
      .map((row) => [...row])
      .sort((left, right) => compareDetailValues(left[columnIndex], right[columnIndex], type) * direction)
      .map((row, index) => row.map((cell, cellIndex) => (cellIndex === 0 ? String(index + 1) : cell)));
  } else {
    state.rows = state.baseRows.map((row) => [...row]);
  }
  const table = detailInfoCard?.querySelector(`[data-detail-table="${CSS.escape(itemId)}"]`);
  table?.querySelectorAll(".detail-sort-button").forEach((button) => {
    const th = button.closest("th");
    const isActive = Boolean(sort) && button.dataset.detailSort === sort.column;
    th?.classList.toggle("is-sorted", isActive);
    if (th) {
      if (isActive) th.setAttribute("data-sort-direction", sort.direction);
      else th.removeAttribute("data-sort-direction");
      th.setAttribute("aria-sort", isActive ? (sort.direction === "asc" ? "ascending" : "descending") : "none");
    }
    button.title = getDetailSortLabel(button.dataset.detailSort, isActive ? sort.direction : "");
  });
  renderDetailPage(itemId, 1);
}

function renderDetailPage(itemId, requestedPage) {
  const state = detailPaginationState.get(itemId);
  if (!state) return;
  const currentPage = Math.min(state.pageCount, Math.max(1, requestedPage));
  state.currentPage = currentPage;
  const table = detailInfoCard?.querySelector(`[data-detail-table="${CSS.escape(itemId)}"]`);
  const tbody = table?.querySelector("tbody");
  if (tbody) {
    const start = (currentPage - 1) * detailPageSize;
    tbody.innerHTML = brand(renderDetailTableRows(state.rows.slice(start, start + detailPageSize), state.item.id));
  }
  const pagination = detailInfoCard?.querySelector(`[data-detail-pagination="${CSS.escape(itemId)}"]`);
  if (pagination) pagination.outerHTML = renderDetailPagination(state.item, currentPage, state.pageCount, state.rows.length);
  syncDetailExpandables();
}

