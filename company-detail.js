function getDetailPaginationPages(currentPage, pageCount) {
  const pages = new Set([1, pageCount, currentPage - 1, currentPage, currentPage + 1]);
  return [...pages].filter((page) => page >= 1 && page <= pageCount).sort((a, b) => a - b);
}

function renderDetailPagination(item, currentPage, pageCount, totalRows) {
  if (pageCount <= 1) return "";
  const pages = getDetailPaginationPages(currentPage, pageCount);
  let lastPage = 0;
  const pageButtons = pages.map((page) => {
    const ellipsis = lastPage && page - lastPage > 1 ? '<span aria-hidden="true">...</span>' : "";
    lastPage = page;
    return `${ellipsis}<button type="button" data-detail-page="${page}" data-detail-page-id="${escapeDetailHtml(item.id)}" class="${page === currentPage ? "is-current" : ""}" aria-current="${page === currentPage ? "page" : "false"}">${page}</button>`;
  }).join("");
  return `<nav class="detail-pagination" data-detail-pagination="${escapeDetailHtml(item.id)}" aria-label="${escapeDetailHtml(item.label)}分页"><span class="detail-pagination-total">共 ${totalRows} 条</span><div class="detail-pagination-controls"><button type="button" data-detail-page="${Math.max(1, currentPage - 1)}" data-detail-page-id="${escapeDetailHtml(item.id)}" aria-label="上一页" ${currentPage === 1 ? "disabled" : ""}>上一页</button>${pageButtons}<button type="button" data-detail-page="${Math.min(pageCount, currentPage + 1)}" data-detail-page-id="${escapeDetailHtml(item.id)}" aria-label="下一页" ${currentPage === pageCount ? "disabled" : ""}>下一页</button></div></nav>`;
}

