function parseDetailNumeric(value) {
  const match = String(value ?? "").replace(/,/g, "").match(/-?\d+(?:\.\d+)?/);
  return match ? Number(match[0]) : Number.NaN;
}

function compareDetailValues(left, right, type) {
  if (type === "percent" || type === "number") {
    const leftNumber = parseDetailNumeric(left);
    const rightNumber = parseDetailNumeric(right);
    if (Number.isNaN(leftNumber) && Number.isNaN(rightNumber)) return 0;
    if (Number.isNaN(leftNumber)) return -1;
    if (Number.isNaN(rightNumber)) return 1;
    return leftNumber - rightNumber;
  }
  const leftText = String(left ?? "").trim();
  const rightText = String(right ?? "").trim();
  if (leftText === rightText) return 0;
  if (!leftText || leftText === "-") return -1;
  if (!rightText || rightText === "-") return 1;
  return leftText < rightText ? -1 : 1;
}

