function splitPartyNames(text) {
  return String(text).split(/[；;]/).map((name) => name.trim()).filter(Boolean);
}

function parseLegalPartyItems(value) {
  const lines = String(value).split("\n").map((line) => line.trim()).filter(Boolean);
  const items = [];
  let pendingRole = "";
  lines.forEach((line) => {
    const match = line.match(/^([^：:]{1,8})[：:]\s*(.*)$/);
    if (match && !match[2].trim()) {
      pendingRole = `${match[1]}：`;
      return;
    }
    if (match) {
      items.push({ role: `${match[1]}：`, names: splitPartyNames(match[2]) });
      pendingRole = "";
      return;
    }
    items.push({ role: pendingRole, names: splitPartyNames(line) });
    pendingRole = "";
  });
  return items.filter((item) => item.names.length || item.role);
}

